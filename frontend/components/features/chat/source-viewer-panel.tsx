"use client";

import React from "react";
import { ArrowLeft, ArrowRight, ExternalLink, FileText, X } from "lucide-react";
import type { RAGSource } from "@/lib/types";
import { formatSourceLocation } from "@/lib/document-workspace";
import styles from "./source-viewer-panel.module.css";

interface SourceViewerPanelProps {
  sources: RAGSource[];
  activeSourceIndex: number;
  onSelectSourceIndex: (index: number) => void;
  onClose: () => void;
  onOpenDocument?: (documentId: string, page: number) => void;
  associatedContent?: string;
}

function extractHeading(source: RAGSource): string {
  const locator = source.locator;
  if (locator && Array.isArray(locator.heading_path) && locator.heading_path.length > 0) {
    return String(locator.heading_path[locator.heading_path.length - 1]).toUpperCase();
  }
  if (source.page_number) {
    return `PAGE ${source.page_number} EVIDENCE`;
  }
  return "PASSAGE EXCERPT";
}

function extractPassageText(source: RAGSource, associatedContent?: string): string {
  if (source.locator && typeof source.locator.snippet === "string" && source.locator.snippet) {
    return source.locator.snippet;
  }
  // If the source has native text attached
  if ("text" in source && typeof (source as unknown as { text: unknown }).text === "string") {
    return (source as unknown as { text: string }).text;
  }
  // Fallback: extract the sentence or bullet from the assistant answer citing [position]
  if (associatedContent) {
    const pos = source.position;
    const regex = new RegExp(`([^.!?\\n]+?\\[${pos}\\])`, "i");
    const match = associatedContent.match(regex);
    if (match) {
      return match[1].replace(new RegExp(`\\s*\\[${pos}\\]`, "g"), "").trim();
    }
  }
  return `Evidence passage from ${source.filename} (${formatSourceLocation(source)}) verified with ${Math.round(source.similarity * 100)}% match confidence.`;
}

export function SourceViewerPanel({
  sources,
  activeSourceIndex,
  onSelectSourceIndex,
  onClose,
  onOpenDocument,
  associatedContent,
}: SourceViewerPanelProps) {
  if (!sources || sources.length === 0) return null;

  const currentSource = sources[activeSourceIndex] || sources[0];
  const pageNumber = currentSource.page_number || 1;
  const heading = extractHeading(currentSource);
  const passage = extractPassageText(currentSource, associatedContent);

  const hasPrev = activeSourceIndex > 0;
  const hasNext = activeSourceIndex < sources.length - 1;

  return (
    <aside className={styles.panel} aria-label="Evidence Source Inspector">
      <div className={styles.header}>
        <div className={styles.fileIconWrap}>
          <FileText size={18} className={styles.fileIcon} />
        </div>
        <div className={styles.headerInfo}>
          <strong className={styles.filename} title={currentSource.filename}>
            {currentSource.filename}
          </strong>
          <span className={styles.subtitle}>
            Source {activeSourceIndex + 1} of {sources.length} · {formatSourceLocation(currentSource)}
          </span>
        </div>
        <button
          type="button"
          className={styles.closeButton}
          onClick={onClose}
          aria-label="Close source preview"
          title="Close preview"
        >
          <X size={16} />
        </button>
      </div>

      <div className={styles.content}>
        <div className={styles.sectionLabel}>{heading}</div>
        <div className={styles.highlightCard}>
          <p className={styles.passageText}>{passage}</p>
        </div>
      </div>

      <div className={styles.footer}>
        <div className={styles.pagination}>
          <button
            type="button"
            className={styles.pageButton}
            onClick={() => onSelectSourceIndex(activeSourceIndex - 1)}
            disabled={!hasPrev}
          >
            <ArrowLeft size={14} />
            <span>Previous</span>
          </button>
          <button
            type="button"
            className={styles.pageButton}
            onClick={() => onSelectSourceIndex(activeSourceIndex + 1)}
            disabled={!hasNext}
          >
            <span>Next</span>
            <ArrowRight size={14} />
          </button>
        </div>

        {onOpenDocument && (
          <button
            type="button"
            className={styles.openFullButton}
            onClick={() => onOpenDocument(currentSource.document_id, pageNumber)}
          >
            <span>Open full document at page {pageNumber}</span>
            <ExternalLink size={14} />
          </button>
        )}

        <p className={styles.disclaimer}>
          Citations are generated by the server from retrieved passages, so every source here comes from your uploaded documents.
        </p>
      </div>
    </aside>
  );
}
